"""Trains (1) laptop model: RandomForest  (2) edge model: small DecisionTree exported to C."""
import pandas as pd, numpy as np, joblib, json
from sklearn.ensemble import RandomForestClassifier
from sklearn.tree import DecisionTreeClassifier
from sklearn.metrics import classification_report, f1_score
from features import add_features, FEATURES

d = pd.read_csv("dataset.csv").rename(columns={"voltage_V":"voltage","current_A":"current",
                                              "power_W":"power","temperature_C":"temperature"})
X, y = add_features(d), d.anomaly_label
# Evaluation: 5-fold StratifiedGroupKFold on 250-row (~21 min) time blocks,
# so neighbouring windows never sit on both sides of a split.
from sklearn.model_selection import StratifiedGroupKFold, cross_val_predict
groups = np.arange(len(d)) // 250
cv = StratifiedGroupKFold(n_splits=5, shuffle=True, random_state=42)

rf = RandomForestClassifier(n_estimators=300, class_weight="balanced_subsample",
                            min_samples_leaf=2, random_state=42, n_jobs=-1)
dt = DecisionTreeClassifier(max_depth=7, min_samples_leaf=3, random_state=42)
rep = {}
for name, m in [("laptop_random_forest", rf), ("edge_decision_tree", dt)]:
    p = cross_val_predict(m, X, y, cv=cv, groups=groups)
    print(f"\n=== {name} (5-fold grouped CV, out-of-fold) ===")
    print(classification_report(y, p, digits=3, zero_division=0))
    rep[name] = classification_report(y, p, output_dict=True, zero_division=0)

# final models trained on all data
rf.fit(X, y); dt.fit(X, y)
joblib.dump({"model": rf, "features": FEATURES}, "model_rf.joblib")
json.dump(rep, open("metrics.json", "w"), indent=1)

# ---- export decision tree to C ----
t, cls = dt.tree_, list(dt.classes_)
def node(i, ind):
    if t.children_left[i] == -1:
        return f"{ind}return {int(np.argmax(t.value[i][0]))};\n"
    return (f"{ind}if (f[{t.feature[i]}] <= {t.threshold[i]:.6f}f) {{\n" + node(t.children_left[i], ind+"  ")
            + f"{ind}}} else {{\n" + node(t.children_right[i], ind+"  ") + f"{ind}}}\n")
labels = ", ".join(f'"{c}"' for c in cls)
open("../firmware/voltguard_esp32/edge_model.h", "w").write(
f"""// AUTO-GENERATED by ml/train.py - edge DecisionTree (depth 7)
// features: {FEATURES}
#pragma once
static const char* EDGE_LABELS[] = {{{labels}}};
static int edgePredict(const float* f) {{
{node(0, "  ")}}}
""")
# Real-hardware sanity check: values_or.csv (your bulb, no faults). Energized rows should be "normal".
r = pd.read_csv("real_values_or.csv").rename(columns={"voltage_V":"voltage","current_A":"current",
                                                     "power_W":"power","temperature_C":"temperature"})
r = r[r.voltage > 0].reset_index(drop=True)
rp = rf.predict(add_features(r)); print("\nReal bulb data (", len(r), "energized rows) -> RF predicted normal:",
      round((rp == "normal").mean()*100, 1), "%  | edge tree:", round((dt.predict(add_features(r)) == "normal").mean()*100, 1), "%")
print("\nclasses:", cls, "\nwrote model_rf.joblib, metrics.json, edge_model.h")
